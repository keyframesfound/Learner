/* Builds db/seed-f2.sql from content/f2/*.json. Run: node scripts/gen-f2-seed.mjs */
import { readdirSync, readFileSync } from "node:fs";

const dir = new URL("../content/f2/", import.meta.url);
const files = readdirSync(dir)
  .filter((f) => /^\d+\.\d+\.json$/.test(f))
  .sort((a, b) => {
    const [ca, la] = a.replace(".json", "").split(".").map(Number);
    const [cb, lb] = b.replace(".json", "").split(".").map(Number);
    return ca - cb || la - lb;
  });

const q = (s) => "$j$" + String(s).replaceAll("$j$", "") + "$j$";
const slugOf = (title, id) =>
  (title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 40) || "lesson") +
  "-" + id.replace(".", "-");

const out = [];
out.push("-- generated by scripts/gen-f2-seed.mjs — do not hand-edit");
out.push("begin;");
out.push(`insert into tracks (id, name, accent, ord) values ('science', 'Science', '#0F7A35', 2)
  on conflict (id) do update set name = excluded.name, accent = excluded.accent;`);
out.push(`insert into modules (id, track_id, code, name, paper, compulsory, exam_weight, ord)
  values ('sci.f2', 'science', 'F2', 'F2 Science', null, true, 0, 1)
  on conflict (id) do update set name = excluded.name, code = excluded.code;`);

files.forEach((file, idx) => {
  const j = JSON.parse(readFileSync(new URL(file, dir), "utf8"));
  const slug = slugOf(j.title, j.id);
  const concepts = [slug.slice(0, 40)];

  out.push(`insert into lessons (module_id, slug, title, summary, minutes, concepts, status, ord)
    values ('sci.f2', ${q(slug)}, ${q(j.title)}, '', ${Math.min(8, Math.max(2, j.minutes || 4))},
            array[${concepts.map(q).join(", ")}], 'published', ${idx + 1})
    on conflict (module_id, slug) do update
      set title = excluded.title, ord = excluded.ord, status = 'published';`);

  let ord = 1;
  const blocks = [];
  for (const note of j.notes || []) {
    blocks.push({ kind: "prose", level: null, ord: ord++, payload: JSON.stringify({ md: note }) });
  }
  if (j.table?.head?.length) {
    const line = (cells) => "| " + cells.join(" | ") + " |";
    const md = [line(j.table.head), ...(j.table.rows || []).map(line)].join("\n");
    blocks.push({ kind: "prose", level: null, ord: ord++, payload: JSON.stringify({ md }) });
  }
  if (j.callout) {
    blocks.push({ kind: "callout", level: null, ord: ord++, payload: JSON.stringify({ tone: "tip", md: j.callout }) });
  }
  for (const [k, item] of (j.questions || []).entries()) {
    blocks.push({
      kind: "mcq",
      level: k === 0 ? "recall" : k === 1 ? "apply" : "apply",
      ord: ord++,
      payload: JSON.stringify({
        prompt: item.prompt,
        ...(item.code?.length ? { code: item.code } : {}),
        options: item.options.map((o) => ({ text: o.text, ...(o.code ? { code: true } : {}) })),
        answer: item.answer,
        why: item.why,
        wrongWhy: item.wrongWhy,
      }),
    });
  }

  const values = blocks
    .map((b) => `('${b.kind}'::block_kind, ${b.level ? `'${b.level}'::item_level` : "null"}, ${b.ord}, ${q(b.payload)})`)
    .join(",\n");

  /* only fill a lesson that has no blocks yet: never clobber attempts or edits */
  out.push(`insert into blocks (lesson_id, kind, level, ord, payload)
    select l.id, v.kind, v.level, v.ord, v.payload::jsonb
      from lessons l
      cross join (values
${values}
      ) as v(kind, level, ord, payload)
     where l.module_id = 'sci.f2' and l.slug = ${q(slug)}
       and not exists (select 1 from blocks b where b.lesson_id = l.id);`);
});

out.push("commit;");
console.log(out.join("\n"));
