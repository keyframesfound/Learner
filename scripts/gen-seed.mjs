/* Builds db/seed.sql from lib/content.ts. Run with: bun scripts/gen-seed.mjs */
import { lessons, bank, subjects } from "../lib/content.ts";

const q = (s) => "$j$" + s + "$j$";
const strip = (s) => s.replace(/<[^>]+>/g, "");
const hasCode = (s) => /<code>/.test(s);

const levelFor = (i) => (i < 2 ? "recall" : i < 4 ? "apply" : "construct");

const byTopic = new Map();
for (const item of bank) {
  if (!byTopic.has(item.topic)) byTopic.set(item.topic, []);
  byTopic.get(item.topic).push(item);
}

const out = [];
out.push("-- generated by scripts/gen-seed.mjs — do not hand-edit");
out.push("begin;");

for (const [i, s] of subjects.entries()) {
  out.push(
    `insert into tracks (id, name, accent, ord) values ('${s.id}', '${s.name}', '${s.colour}', ${i})
     on conflict (id) do update set name = excluded.name, accent = excluded.accent, ord = excluded.ord;`,
  );
}

out.push(
  `insert into modules (id, track_id, code, name, paper, compulsory, exam_weight, ord)
   values ('ict.e2c', 'ict', 'E2C', 'Programming basics', 1, true, 0.35, 1)
   on conflict (id) do update set name = excluded.name, code = excluded.code;`,
);

for (const [i, l] of lessons.entries()) {
  const topic = l.title;
  const items = byTopic.get(topic) ?? [];
  out.push(
    `insert into lessons (module_id, slug, title, summary, minutes, concepts, status, ord)
     values ('ict.e2c', '${l.id}', ${q(l.title)}, '', 4, array['${l.id}'], 'published', ${i + 1})
     on conflict (module_id, slug) do update set title = excluded.title, ord = excluded.ord;`,
  );

  if (items.length) {
    /* one statement per lesson, so the "no blocks yet" guard is evaluated once */
    const values = items.map((it, k) => {
      const options = it.a.map((text) => ({
        text: strip(text).trim(),
        ...(hasCode(text) ? { code: true } : {}),
      }));
      const answerText = options[it.c]?.text ?? "";
      const payload = {
        prompt: strip(it.q).trim(),
        options,
        answer: it.c,
        why: `The answer is ${answerText}.`,
        wrongWhy: `The correct answer is ${answerText}.`,
      };
      return `('mcq', '${levelFor(k)}', ${k + 1}, ${q(JSON.stringify(payload))})`;
    });
    out.push(
      `insert into blocks (lesson_id, kind, level, ord, payload)
       select l.id, v.kind::block_kind, v.level::item_level, v.ord, v.payload::jsonb
         from lessons l
         cross join (values ${values.join(", ")}) as v(kind, level, ord, payload)
        where l.slug = '${l.id}' and l.module_id = 'ict.e2c'
          and not exists (select 1 from blocks b where b.lesson_id = l.id);`,
    );
  }
}

out.push("commit;");
console.log(out.join("\n"));
